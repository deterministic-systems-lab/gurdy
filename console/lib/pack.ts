/** Cedar pack builder. Mirrors policy/pack.py render_cedar so a full
 *  catalog publish hashes the same as `python3 policy/pack.py generate`.
 *  Safe in the browser: no filesystem, no crypto.
 */

export type PathGlob = { glob: string; note: string };
export type DestructiveTool = { op: "eq" | "like"; value: string; shell: boolean };
export type ShellAlias = {
  command: string;
  tool: string;
  forbid: boolean;
  note: string;
};

export type ControlsDoc = {
  version: number;
  ids: {
    credential_read: string;
    sensitive_write: string;
    destructive_fs: string;
    named_tools: string;
    unlisted_model_host: string;
  };
  credential_paths: PathGlob[];
  write_paths: PathGlob[];
  destructive_tools: DestructiveTool[];
  shell_aliases: ShellAlias[];
  unlisted_model_host: boolean;
};

